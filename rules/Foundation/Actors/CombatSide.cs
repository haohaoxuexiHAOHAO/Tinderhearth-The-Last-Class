namespace Tinderhearth.Rules.Foundation.Actors;

/// <summary>
/// 一个角色此刻站在哪一边。**表达的是当前的敌我关系，不是族群归属。**
/// </summary>
/// <remarks>
/// **命名有一条世界观红线要避开。** 正典（设计仓 `canon/world/世界观.md`）明确写了魔化生物
/// 「**不是一个阵营**」，理由是「魔化是状态，不是某个族群的天性」。把魔化写成阵营会同时废掉
/// 「魔化可被中断」与「支持、照护与共同承担能中断闭环」这两条叙事承重项，还会让「一个正在魔化
/// 的学生」这类情节只剩处理掉一条出路。所以本枚举说的是**这一场里谁跟谁对着打**：一个正在魔化
/// 的学生可以此刻是 <see cref="Enemy"/>、被中断之后是 <see cref="Ally"/>，而他的族群一天都没变。
/// 命名与注释都不该让它读成后者。
///
/// **为什么落在 `Foundation.Actors` 而不是 `Combat`**：它不只给阻挡用。正典的迷雾与视野
/// （`canon/gameplay/战斗与关卡.md`）已经拿阵营做敌我判定（「敌人与可交互物件只在**阵营视野
/// 并集**内显形」「友方视野取并集，敌方独立取并集」），将来的感知系统要读**同一份**。`GP-17`
/// 只是第一个需要它的系统，不是唯一一个 —— 落在角色身份这一层，感知系统就不必再造一份，而
/// 「各建一套」的表现是两处对敌我的判断悄悄不一致。
///
/// **参照系是玩家那一方**：<see cref="Ally"/> 指「与玩家同一边」。这与 `ENG-5` 那条「玩家不是
/// 主角的同义词」不冲突 —— 这里说的是立场，不是谁在驱动那个角色；主角与队友都可以由 AI 驱动而
/// 仍然是 <see cref="Ally"/>。**真正的多方势力**（甲乙丙互相敌对、且关系会变）需要的是一张关系
/// 矩阵而不是三个值，等有那种关卡再说：现在造矩阵是凭空猜关系。
/// </remarks>
public enum CombatSide
{
    /// <summary>与玩家同一边：主角、队友、友方 NPC。</summary>
    Ally,

    /// <summary>此刻与玩家敌对。**是当前关系，不是族群标签**，理由见类型说明。</summary>
    Enemy,

    /// <summary>不站边的东西：场景障碍物、可采集资源这一类。谁都挡，谁都不帮。</summary>
    Neutral,
}
